const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const source = fs.readFileSync('static/app.js', 'utf8');
const grab = name => { const start = source.indexOf(`function ${name}(`); return source.slice(start, source.indexOf('\n}\n', start) + 2); };
let now = 1000, next = 0;
const timers = new Map(), handlers = {}, classes = new Set();
const cover = {classList: {add: k => classes.add(k), remove: k => classes.delete(k), contains: k => classes.has(k)}, addEventListener: (type, fn) => handlers[type] = fn};
const context = vm.createContext({Date: {now: () => now}, setTimeout: (fn, delay) => {timers.set(++next, {fn, at: now + delay}); return next;}, clearTimeout: id => timers.delete(id)});
const tick = ms => { now += ms; for (const [id, timer] of [...timers]) if (timer.at <= now) {timers.delete(id); timer.fn();} };
vm.runInContext(grab('bindSideVideoControls'), context);
context.bindSideVideoControls(cover);
handlers.pointerenter({type: 'pointerenter', pointerType: 'mouse'});
assert.ok(classes.has('show-video-controls'));
tick(3100); assert.ok(!classes.has('show-video-controls'), 'stationary hover does not pin controls');
handlers.pointermove({type: 'pointermove', pointerType: 'mouse'}); tick(2500);
handlers.pointermove({type: 'pointermove', pointerType: 'mouse'}); tick(1000);
assert.ok(classes.has('show-video-controls'), 'movement resets the timeout');
handlers.pointerleave(); assert.ok(!classes.has('show-video-controls'));
handlers.pointerenter({type: 'pointerenter', pointerType: 'touch'});
handlers.pointerdown({type: 'pointerdown', pointerType: 'touch'});
let prevented = false;
handlers.click({target: {closest: () => true}, preventDefault(){prevented=true;}, stopPropagation(){}});
assert.ok(prevented, 'first touch reveals controls without toggling video');
tick(500); prevented = false;
handlers.click({target: {closest: () => true}, preventDefault(){prevented=true;}, stopPropagation(){}});
assert.ok(!prevented, 'second tap activates controls');
tick(3000); assert.ok(!classes.has('show-video-controls'), 'touch controls auto-hide');
const button = {classList:{toggle(){}}, hidden:true}, refresh = {};
context.state={currentTrack:{title:'Song'},videoMode:false, videoFetch:{status:'not_found'}};
context.$=id=>id==='sideVideoSwitch'?button:refresh;
context.canSwitchToLocalVideo=()=>false;context.canSwitchToVideo=()=>true;context.renderVideoSyncControls=()=>{};
vm.runInContext(grab('renderSideVideoButton'),context); context.renderSideVideoButton();
assert.match(button.innerHTML,/No video available/);assert.ok(button.disabled);assert.equal(button.hidden,false);
context.state.videoFetch.status='error'; context.renderSideVideoButton();
assert.match(button.innerHTML,/Retry video/);assert.ok(!button.disabled,'a failed preview can be retried');
console.log('Video controls hide after inactivity; static artwork shows No video available; preview errors stay retryable');
